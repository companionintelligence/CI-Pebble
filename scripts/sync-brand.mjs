#!/usr/bin/env node
/**
 * sync-brand.mjs: writes every brand-derived file in this repo from the pinned,
 * hash-checked bundle in vendor/brand/ (see vendor/brand/.brand-source).
 *
 *   node scripts/sync-brand.mjs           regenerate
 *   node scripts/sync-brand.mjs --check   fail if anything on disk has drifted
 *
 * Nothing it writes is hand-maintained. Change the canon in CI-Common, bump the
 * pinned bundle (scripts/vendor-brand.sh), then run this. Node built-ins only.
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync, copyFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const V = join(ROOT, 'vendor/brand');
const CHECK = process.argv.includes('--check');
const drift = [];

const sha = (buf) => createHash('sha256').update(buf).digest('hex');

// 1. The vendored bundle must match its own SHA256SUMS before anything is derived from it.
for (const line of readFileSync(join(V, 'SHA256SUMS'), 'utf8').trim().split('\n')) {
  const [want, path] = line.split(/\s+/);
  if (sha(readFileSync(join(V, path))) !== want) {
    console.error(`vendor/brand/${path} does not match SHA256SUMS. Re-run scripts/vendor-brand.sh.`);
    process.exit(2);
  }
}

const tokens = JSON.parse(readFileSync(join(V, 'tokens/tokens.json'), 'utf8'));
const copy = JSON.parse(readFileSync(join(V, 'copy.json'), 'utf8'));
const version = readFileSync(join(V, '.version'), 'utf8').trim();

function emit(path, content) {
  const abs = join(ROOT, path);
  const current = existsSync(abs) ? readFileSync(abs) : null;
  const next = Buffer.isBuffer(content) ? content : Buffer.from(content);
  if (current && sha(current) === sha(next)) return;
  if (CHECK) { drift.push(path); return; }
  mkdirSync(dirname(abs), { recursive: true });
  writeFileSync(abs, next);
  console.log(`wrote ${path}`);
}

const hex = (mode, name) => tokens[mode][name].hex.replace('#', '0x');

// 2. C header for the watch app (Pebble quantises to its 64-colour palette at build time).
const cNames = [
  ['PRIMARY', 'primary'], ['PRIMARY_FOREGROUND', 'primary-foreground'],
  ['BACKGROUND', 'background'], ['FOREGROUND', 'foreground'],
  ['MUTED_FOREGROUND', 'muted-foreground'], ['DESTRUCTIVE', 'destructive'],
];
emit('src/c/brand.h', [
  `/* GENERATED by scripts/sync-brand.mjs from @companionintelligence/tokens ${version}. Do not edit. */`,
  '#pragma once',
  ...['light', 'dark'].flatMap((m) => cNames.map(([c, t]) => `#define CI_${m.toUpperCase()}_${c} ${hex(m, t)}`)),
  '',
].join('\n'));

// 3. Brand block inside the phone companion (settings page CSS + logo), between markers.
const logo = readFileSync(join(V, 'logos/mark-tight.svg'), 'utf8').replace(/<\?xml[^>]*>/, '').replace(/\s+/g, ' ').trim();
const cssVars = (m) => [
  ...['background', 'foreground', 'card', 'primary', 'primary-foreground', 'muted', 'muted-foreground', 'border', 'destructive']
    .map((n) => `--${n}:${tokens[m][n].hex}`),
  ...['success', 'warning'].map((n) => `--${n}:${tokens.status[m][n].hex}`),
].join(';');
const block = [
  '/* BEGIN GENERATED brand (scripts/sync-brand.mjs, tokens ' + version + '). Do not edit. */',
  'var CI_BRAND_LIGHT_CSS = ' + JSON.stringify(cssVars('light')) + ';',
  'var CI_BRAND_DARK_CSS = ' + JSON.stringify(cssVars('dark')) + ';',
  'var CI_BRAND_MARK_SVG = ' + JSON.stringify(logo) + ';',
  'var CI_BRAND_PRODUCT = ' + JSON.stringify(copy.products.memory.name) + ';',
  'var CI_BRAND_TAGLINE = ' + JSON.stringify(copy.products.memory.tagline) + ';',
  '/* END GENERATED brand */',
].join('\n');
{
  const path = join(ROOT, 'src/js/pebble-js-app.js');
  const src = readFileSync(path, 'utf8');
  const re = /\/\* BEGIN GENERATED brand[\s\S]*?\/\* END GENERATED brand \*\//;
  if (!re.test(src)) { console.error('markers missing in src/js/pebble-js-app.js'); process.exit(2); }
  emit('src/js/pebble-js-app.js', src.replace(re, () => block));
}

// 3b. README tagline, from the copy tokens (never typed by hand).
{
  const path = join(ROOT, 'README.md');
  const src = existsSync(path) ? readFileSync(path, 'utf8') : '';
  const re = /<!-- BEGIN GENERATED tagline -->[\s\S]*?<!-- END GENERATED tagline -->/;
  if (re.test(src)) {
    emit('README.md', src.replace(re, () => `<!-- BEGIN GENERATED tagline -->\n**${copy.products.memory.tagline}**\n<!-- END GENERATED tagline -->`));
  }
}

// 4. Site: static assets copied byte for byte, page rendered from its template + copy tokens.
const assets = [
  ['tokens/tokens.css', 'tokens.css'], ['fonts/manrope-latin-var.woff2', 'manrope.woff2'],
  ['fonts/jetbrains-mono-latin-var.woff2', 'jetbrains-mono.woff2'], ['fonts/LICENSE-Manrope.txt', 'LICENSE-Manrope.txt'],
  ['fonts/LICENSE-JetBrains-Mono.txt', 'LICENSE-JetBrains-Mono.txt'], ['logos/mark-tight.svg', 'mark.svg'],
  ['logos/lockup.svg', 'lockup.svg'], ['logos/lockup-on-light.svg', 'lockup-on-light.svg'],
];
for (const [from, to] of assets) emit(`site/assets/brand/${to}`, readFileSync(join(V, from)));

// 4b. Icons the page links to (PNG favicon, apple-touch-icon, JSON-LD logo), copied byte for byte from the
// store icons that scripts/render-icons.mjs draws, so the site can never drift from them.
for (const [from, to] of [
  ['icon-48.png', 'icon-48.png'], ['icon-512.png', 'icon-512.png'], ['icon-touch-180.png', 'apple-touch-icon.png'],
]) emit(`site/assets/${to}`, readFileSync(join(ROOT, 'assets/appstore/icon', from)));

// 4c. Web app manifest, from the copy tokens (names are never typed by hand).
emit('site/site.webmanifest', JSON.stringify({
  name: `${copy.products.memory.name} for Pebble`,
  short_name: `${copy.products.memory.name.replace(/^Companion /, '')} for Pebble`,
  description: `Recall and search your ${copy.products.memory.name} from your Pebble. ${copy.products.memory.tagline}`,
  start_url: '/',
  scope: '/',
  display: 'browser',
  background_color: tokens.light.background.hex,
  theme_color: tokens.light.background.hex,
  icons: [
    { src: '/assets/apple-touch-icon.png', sizes: '180x180', type: 'image/png' },
    { src: '/assets/icon-512.png', sizes: '512x512', type: 'image/png' },
  ],
}, null, 2) + '\n');

const tpl = join(ROOT, 'site-src/index.template.html');
if (existsSync(tpl)) {
  const lookup = (p) => p.split('.').reduce((o, k) => (o == null ? o : o[k]), copy);
  const html = readFileSync(tpl, 'utf8').replace(/\{\{\s*([\w.]+)\s*\}\}/g, (_, p) => {
    const v = lookup(p);
    if (typeof v !== 'string') { console.error(`unknown copy token {{${p}}}`); process.exit(2); }
    return v;
  });
  emit('site/index.html', html);
}

if (CHECK && drift.length) {
  console.error('Brand-derived files are out of date:\n  ' + drift.join('\n  ') + '\nRun: node scripts/sync-brand.mjs');
  process.exit(1);
}
if (CHECK) console.log('brand-derived files are in sync');
